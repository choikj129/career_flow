import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { describe, expect, test } from 'vitest';
import { extractPostingText, looksBlocked, MIN_POSTING_TEXT_LENGTH } from '@/lib/extract/extract-posting';
import { isBrowserBusy, withBrowser } from '@/lib/extract/browser';

const FULL = resolve(__dirname, 'fixtures/posting-full.html');
const EMPTY = resolve(__dirname, 'fixtures/posting-empty.html');
const tmpProfile = () => mkdtempSync(join(tmpdir(), 'cf-profile-'));

describe('extractPostingText', () => {
  test('extracts JS-rendered text from page', async () => {
    const r = await extractPostingText(pathToFileURL(FULL).href, { profileDir: tmpProfile(), allowNonHttpUrl: true });
    expect(r.text).toContain('자격요건');
    expect(r.text.length).toBeGreaterThanOrEqual(MIN_POSTING_TEXT_LENGTH);
    expect(r.title).toContain('서버 개발자');
  }, 60_000);

  test('fails on too-short text', async () => {
    await expect(
      extractPostingText(pathToFileURL(EMPTY).href, { profileDir: tmpProfile(), allowNonHttpUrl: true }),
    ).rejects.toMatchObject({ kind: 'extract_failed' });
  }, 60_000);

  test('TC-NEW-12 http(s)가 아닌 주소는 브라우저를 열기 전에 거부한다', async () => {
    for (const u of ['file:///C:/Windows/win.ini', 'javascript:alert(1)', 'ftp://example.com/a']) {
      await expect(extractPostingText(u, { profileDir: tmpProfile() }), u).rejects.toMatchObject({
        kind: 'extract_failed',
        message: expect.stringContaining('올바른 공고 주소가 아닙니다'),
      });
    }
  });

  test('fails on unreachable url as extract_failed', async () => {
    await expect(
      extractPostingText('http://127.0.0.1:1/none', { profileDir: tmpProfile(), timeoutMs: 5000 }),
    ).rejects.toMatchObject({ kind: 'extract_failed' });
  }, 60_000);
});

describe('withBrowser', () => {
  test('serializes concurrent browser use', async () => {
    const spans: { start: number; end: number }[] = [];
    const run = () =>
      withBrowser(
        async () => {
          const start = Date.now();
          await new Promise((r) => setTimeout(r, 100));
          spans.push({ start, end: Date.now() });
        },
        { profileDir: tmpProfile() },
      );
    const p1 = run();
    const p2 = run();
    expect(isBrowserBusy()).toBe(true);
    await Promise.all([p1, p2]);
    expect(spans).toHaveLength(2);
    expect(spans[1].start).toBeGreaterThanOrEqual(spans[0].end);
    expect(isBrowserBusy()).toBe(false);
  }, 60_000);
});

describe('looksBlocked', () => {
  // 2026-11-18 실제 확인: 원티드가 자동 브라우저에 CloudFront 403 오류 페이지(512자)를 돌려줬다.
  test('detects a CDN block page even when it is longer than the minimum length', () => {
    const cloudfront =
      '403 ERROR\nThe request could not be satisfied.\nRequest blocked. We can not connect to the server for this app or website at this time. ' +
      'There might be too much traffic or a configuration error. Try again later, or contact the app or website owner.\n' +
      'If you provide content to customers through CloudFront, you can find steps to troubleshoot and help prevent this error by reviewing the CloudFront documentation.\n' +
      'Generated by cloudfront (CloudFront)\nRequest ID: abc';
    expect(looksBlocked(cloudfront)).toBe(true);
    expect(looksBlocked('Access Denied\nYou do not have permission to access this page.')).toBe(true);
    expect(looksBlocked('Just a moment...\nChecking your browser before accessing the site.')).toBe(true);
  });
  test('does not flag a normal long posting that merely mentions an error', () => {
    const posting = '서버 개발자 채용\n' + '주요 업무와 자격 요건을 자세히 적은 본문입니다. '.repeat(120) + '\n오류 처리 경험 (403 ERROR 대응 포함)';
    expect(looksBlocked(posting)).toBe(false);
  });
});
