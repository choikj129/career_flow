// 공고 본문 추출 경계값: 최소 300자, 최대 50,000자. 127.0.0.1 로컬 http 서버로 만든 페이지를 쓴다(외부 접속 없음).
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, test } from 'vitest';
import { startFixtureServer, type FixtureServer } from './helpers/http-fixture';
import {
  extractPostingText,
  looksBlocked,
  MAX_POSTING_TEXT_LENGTH,
  MIN_POSTING_TEXT_LENGTH,
} from '@/lib/extract/extract-posting';

const profile = () => mkdtempSync(join(tmpdir(), 'cf-profile-'));
const html = (text: string) => `<html><body><main>${text}</main></body></html>`;

// 테스트마다 다른 본문이 필요하므로 경로를 늘려 가며 등록한다.
const pages: Record<string, string> = {};
let fx: FixtureServer;
let seq = 0;
beforeAll(async () => {
  fx = await startFixtureServer(pages);
});
afterAll(() => fx.close());
const page = (text: string) => {
  const path = `/p${seq++}`;
  pages[path] = html(text);
  return fx.url(path);
};

describe('본문 길이 경계', () => {
  test('TC-EXTRACT-06 최소 길이 직전(299자)은 실패, 정확히 300자는 성공', async () => {
    expect(MIN_POSTING_TEXT_LENGTH).toBe(300);
    await expect(extractPostingText(page('가'.repeat(299)), { profileDir: profile() })).rejects.toMatchObject({
      kind: 'extract_failed',
    });
    const ok = await extractPostingText(page('가'.repeat(300)), { profileDir: profile() });
    expect(ok.text).toHaveLength(300);
  }, 90_000);

  test('TC-EXTRACT-06 최대 길이를 넘는 본문은 50,000자로 자른다', async () => {
    expect(MAX_POSTING_TEXT_LENGTH).toBe(50_000);
    const r = await extractPostingText(page('가'.repeat(60_000)), { profileDir: profile() });
    expect(r.text).toHaveLength(50_000);
  }, 60_000);

  test('TC-EXTRACT-06 빈 페이지는 추출 실패', async () => {
    await expect(extractPostingText(page(''), { profileDir: profile() })).rejects.toMatchObject({
      kind: 'extract_failed',
    });
  }, 60_000);
});

describe('차단 페이지 감지', () => {
  test.each([
    ['CloudFront 403', '403 ERROR\nThe request could not be satisfied.\nGenerated by cloudfront (CloudFront)'],
    ['Cloudflare 대기', 'Just a moment...\nChecking your browser before accessing the site.'],
    ['접근 거부', "Access Denied\nYou don't have permission to access this resource."],
    ['HTTP 오류 제목', '503 Error\nService unavailable'],
  ])('TC-EXTRACT-05 %s 는 차단 페이지로 본다', (_n, text) => {
    expect(looksBlocked(text)).toBe(true);
  });

  test('TC-EXTRACT-05 평범한 짧은 안내문과 긴 정상 공고는 차단으로 보지 않는다', () => {
    expect(looksBlocked('서버 개발자 채용 공고입니다. 주요업무와 자격요건을 확인하세요.')).toBe(false);
    expect(looksBlocked('Access denied 라는 문구가 있어도 ' + '가'.repeat(2500))).toBe(false);
  });

  test('TC-EXTRACT-07 차단 페이지는 300자를 넘어도 추출 실패 + 붙여넣기 안내', async () => {
    const text = 'The request could not be satisfied. ' + 'Request blocked. Generated by cloudfront. '.repeat(10);
    await expect(extractPostingText(page(text), { profileDir: profile() })).rejects.toMatchObject({
      kind: 'extract_failed',
      message: expect.stringContaining('붙여넣어'),
    });
  }, 60_000);
});
