import { AiError } from '@/lib/ai/runner';
import { assertHttpUrl } from '@/lib/domain/normalize';
import { BROWSER_LOCK_TIMEOUT_MS, BrowserLockTimeoutError, withBrowser } from './browser';

import { MAX_POSTING_TEXT_LENGTH, MIN_POSTING_TEXT_LENGTH } from '@/lib/domain/limits';

export { MAX_POSTING_TEXT_LENGTH, MIN_POSTING_TEXT_LENGTH };

const FAIL_MESSAGE =
  '공고 본문을 읽지 못했습니다(로그인이 필요하거나 페이지 구조가 다를 수 있음). 공고 내용을 붙여넣어 주세요.';

const BROWSER_BUSY_MESSAGE = '브라우저를 다른 작업(PDF 만들기 등)이 쓰고 있습니다. 잠시 뒤 다시 시도하세요';

const BLOCKED_MESSAGE =
  '사이트가 자동 접속을 막았습니다(오류 페이지가 돌아왔습니다). 공고 내용을 복사해 붙여넣어 주세요.';

// CDN·보안 장치가 자동 브라우저에 돌려주는 오류 페이지의 흔한 문구. 오류 페이지는 짧으므로 짧은 글에서만 찾는다.
const BLOCK_PATTERNS: RegExp[] = [
  /^\s*[45]\d\d\s+error\b/i,
  /request blocked/i,
  /the request could not be satisfied/i,
  /generated by cloudfront/i,
  /access denied/i,
  /just a moment\.\.\./i,
  /checking your browser/i,
  /enable javascript and cookies to continue/i,
];

/** 공고 본문이 아니라 차단·오류 페이지로 보이면 true */
export function looksBlocked(text: string): boolean {
  if (text.length > 2000) return false;
  return BLOCK_PATTERNS.some((re) => re.test(text));
}

// 사이트별 선택자는 실제 페이지로 확인한 뒤에만 추가한다(확인되지 않은 선택자는 넣지 않는다).
const SELECTORS = ['main', 'article', 'body'];

function clean(text: string): string {
  return text
    .replace(/\r/g, '')
    .replace(/[ \t ]+/g, ' ')
    .replace(/ ?\n ?/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

export async function extractPostingText(
  url: string,
  opts: { timeoutMs?: number; lockTimeoutMs?: number } = {},
): Promise<{ text: string; title: string }> {
  try {
    assertHttpUrl(url);
  } catch (e) {
    throw new AiError('extract_failed', e instanceof Error ? e.message : String(e));
  }
  try {
    return await withBrowser(
      async (ctx) => {
        const page = await ctx.newPage();
        await page.goto(url, { waitUntil: 'networkidle', timeout: opts.timeoutMs ?? 30_000 });
        const title = (await page.title()).trim();
        let best = '';
        for (const sel of SELECTORS) {
          const el = await page.$(sel);
          if (!el) continue;
          const text = clean(await el.innerText());
          if (text.length > best.length) best = text;
          if (text.length >= MIN_POSTING_TEXT_LENGTH) {
            best = text;
            break;
          }
        }
        if (looksBlocked(best)) throw new AiError('extract_failed', BLOCKED_MESSAGE);
        if (best.length < MIN_POSTING_TEXT_LENGTH) throw new AiError('extract_failed', FAIL_MESSAGE);
        return { text: best.slice(0, MAX_POSTING_TEXT_LENGTH), title };
      },
      { lockTimeoutMs: opts.lockTimeoutMs ?? BROWSER_LOCK_TIMEOUT_MS },
    );
  } catch (e) {
    if (e instanceof AiError) throw e;
    if (e instanceof BrowserLockTimeoutError) throw new AiError('extract_failed', BROWSER_BUSY_MESSAGE);
    throw new AiError('extract_failed', FAIL_MESSAGE);
  }
}
